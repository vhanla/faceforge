#Requires -Version 5.1
<#
.SYNOPSIS
    Run the faceforge benchmark matrix on Windows and write a Markdown summary.

.EXAMPLE
    .\scripts\run_bench.ps1
    .\scripts\run_bench.ps1 -Repeats 10
    .\scripts\run_bench.ps1 -Providers cuda
#>
[CmdletBinding()]
param(
    [int]$Repeats = 5,
    [int]$Warmup = 2,
    [string]$Providers = "cuda,cpu",
    [int]$DetSize = 640,
    [string]$Models = "models",
    [string]$Target = "assets/target_t1.jpg",
    [string]$Source = "assets/source_lena.jpg",
    [string]$Csv = "bench/results/bench.csv",
    [string]$OutMd = "bench/results/latest.md"
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
Push-Location $root
try {
    $bin = Join-Path $root "build\ffbench.exe"
    if (-not (Test-Path $bin)) {
        throw "$bin not found. Run .\scripts\build.ps1 -CoreOnly first."
    }

    $csvPath = Join-Path $root $Csv
    $mdPath = Join-Path $root $OutMd
    New-Item -ItemType Directory -Force -Path (Split-Path $csvPath -Parent) | Out-Null
    if (Test-Path $csvPath) { Remove-Item $csvPath -Force }

    Write-Host "==> GPU / CPU inventory"
    $gpu = $null
    if (Get-Command nvidia-smi -ErrorAction SilentlyContinue) {
        $gpu = (& nvidia-smi --query-gpu=name,memory.total,driver_version,compute_cap --format=csv,noheader) -join " "
        if ($LASTEXITCODE -eq 0) { Write-Host $gpu } else { $gpu = $null }
    }

    function Invoke-Stage {
        param([string[]]$StageArgs)
        Write-Host ""
        Write-Host ">>> ffbench $($StageArgs -join ' ')"
        & $bin --models $Models --target $Target --source $Source `
               --det-size $DetSize --csv $csvPath @StageArgs
        if ($LASTEXITCODE -ne 0) { throw "ffbench failed for: $($StageArgs -join ' ')" }
    }

    foreach ($provider in $Providers.Split(",")) {
        $provider = $provider.Trim()
        if (-not $provider) { continue }

        $extra = @()
        if ($provider -eq "cpu") { $extra += @("--threads", "0") }

        Invoke-Stage (@("--provider", $provider, "--stage", "detect", "--repeats", "$Repeats") + $extra)
        Invoke-Stage (@("--provider", $provider, "--stage", "embed", "--repeats", "$Repeats") + $extra)
        Invoke-Stage (@("--provider", $provider, "--stage", "swap", "--repeats", "$Repeats") + $extra)

        foreach ($enh in @("gfpgan", "esrgan2", "esrgan4")) {
            $reps = $Repeats
            if ($enh -eq "esrgan4" -and $Repeats -gt 3) { $reps = 3 }
            Invoke-Stage (@("--provider", $provider, "--stage", "enhance", "--enhancer", $enh,
                            "--repeats", "$reps") + $extra)
        }

        if ($provider -eq "cuda") {
            Invoke-Stage @("--provider", "cuda", "--stage", "full", "--enhancer", "gfpgan", "--repeats", "$Repeats")
            Invoke-Stage @("--provider", "cuda", "--stage", "full", "--enhancer", "gfpgan", "--repeats", "$Repeats", "--sequential")
        } else {
            Invoke-Stage @("--provider", "cpu", "--stage", "full", "--enhancer", "gfpgan", "--repeats", "1", "--warmup", "1")
        }
    }

    Write-Host ""
    Write-Host "==> writing $OutMd"
    $python = if (Get-Command python -ErrorAction SilentlyContinue) { "python" } else { "py" }
    $stamp = [DateTime]::UtcNow.ToString("yyyy-MM-dd HH:mm 'UTC'")
    $header = @(
        "# faceforge benchmark",
        "",
        "Generated by ``scripts/run_bench.ps1`` on $stamp.",
        "Target: ``$Target``, identity: ``$Source``, det size $DetSize.",
        "**enhance*** measurements use a 512x512 face crop; **pipeline** is the",
        "full image (all detected faces) with swap + enhancer.",
        ""
    )
    if ($gpu) { $header += "GPU: $gpu"; $header += "" }
    $table = & $python (Join-Path $root "scripts\bench_to_md.py") $csvPath
    if ($LASTEXITCODE -ne 0) { throw "bench_to_md.py failed" }
    ($header + $table) | Set-Content -Path $mdPath -Encoding UTF8

    Write-Host ""
    Get-Content $mdPath
} finally {
    Pop-Location
}