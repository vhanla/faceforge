#!/usr/bin/env bash
# Run the benchmark matrix and print a Markdown summary.
#
#   scripts/run_bench.sh                # CUDA + CPU, default repeats
#   REPEATS=10 scripts/run_bench.sh     # more repetitions
#   PROVIDERS=cuda scripts/run_bench.sh # GPU only
#
# Results are appended to bench/results/bench.csv and summarized in
# bench/results/latest.md. Both are small text files and can be committed.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${ROOT}"

BIN="${ROOT}/build/ffbench"
MODELS="${MODELS:-models}"
TARGET="${TARGET:-assets/target_t1.jpg}"
SOURCE="${SOURCE:-assets/source_lena.jpg}"
CSV="${CSV:-bench/results/bench.csv}"
OUT_MD="${OUT_MD:-bench/results/latest.md}"
REPEATS="${REPEATS:-5}"
WARMUP="${WARMUP:-2}"
DET_SIZE="${DET_SIZE:-640}"
PROVIDERS="${PROVIDERS:-cuda cpu}"

if [[ ! -x "${BIN}" ]]; then
  echo "error: ${BIN} not found. Run scripts/build.sh --core first." >&2
  exit 1
fi

mkdir -p "$(dirname "${CSV}")"
rm -f "${CSV}"

echo "==> GPU / CPU inventory"
if command -v nvidia-smi >/dev/null; then
  nvidia-smi --query-gpu=name,memory.total,driver_version,compute_cap \
             --format=csv,noheader || true
fi

run() {
  echo
  echo ">>> ffbench $*"
  "${BIN}" --models "${MODELS}" --target "${TARGET}" --source "${SOURCE}" \
           --det-size "${DET_SIZE}" --csv "${CSV}" "$@"
}

for provider in ${PROVIDERS}; do
  extra=()
  [[ "${provider}" == "cpu" ]] && extra+=(--threads 0)

  run --provider "${provider}" --stage detect --repeats "${REPEATS}" "${extra[@]}"
  run --provider "${provider}" --stage embed  --repeats "${REPEATS}" "${extra[@]}"
  run --provider "${provider}" --stage swap   --repeats "${REPEATS}" "${extra[@]}"

  for enh in gfpgan esrgan2 esrgan4; do
    reps="${REPEATS}"
    # x4 is the slowest stage; keep the default run short.
    [[ "${enh}" == "esrgan4" && "${REPEATS}" -gt 3 ]] && reps=3
    run --provider "${provider}" --stage enhance --enhancer "${enh}" \
        --repeats "${reps}" "${extra[@]}"
  done

  if [[ "${provider}" == "cuda" ]]; then
    run --provider cuda --stage full --enhancer gfpgan --repeats "${REPEATS}"
    run --provider cuda --stage full --enhancer gfpgan --repeats "${REPEATS}" --sequential
  else
    run --provider cpu --stage full --enhancer gfpgan --repeats 1 --warmup 1
  fi
done

echo
echo "==> writing ${OUT_MD}"
{
  echo "# faceforge benchmark"
  echo
  echo "Generated by \`scripts/run_bench.sh\` on $(date -u '+%Y-%m-%d %H:%M UTC')."
  echo "Target: \`${TARGET}\`, identity: \`${SOURCE}\`, det size ${DET_SIZE}."
  echo "**enhance*** measurements use a 512x512 face crop; **pipeline** is the"
  echo "full image (all detected faces) with swap + enhancer."
  echo
  if command -v nvidia-smi >/dev/null; then
    echo "GPU: $(nvidia-smi --query-gpu=name,memory.total,driver_version --format=csv,noheader)"
    echo
  fi
  python3 scripts/bench_to_md.py "${CSV}"
} > "${OUT_MD}"

echo
cat "${OUT_MD}"
